async page => {
  const base='http://127.0.0.1:4321';
  const checks=[];
  const check=(name,pass)=>checks.push({name,pass});
  const today=new Date();
  const date=offset=>{const d=new Date(today);d.setDate(d.getDate()+offset);return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;};
  const preparePhotos=async()=>{
    await page.evaluate(()=>{
      document.querySelectorAll('img[src]').forEach(img=>img.loading='eager');
    });
    await page.waitForFunction(()=>Array.from(document.querySelectorAll('img[src]')).every(img=>img.complete&&img.naturalWidth>0));
    await page.evaluate(async()=>{
      await document.fonts.ready;
      await Promise.all(Array.from(document.querySelectorAll('img[src]')).map(img=>img.decode()));
      for(let y=0;y<document.documentElement.scrollHeight;y+=500){scrollTo({top:y,behavior:'instant'});await new Promise(resolve=>setTimeout(resolve,65));}
      scrollTo({top:0,behavior:'instant'});
    });
    await page.waitForTimeout(1200);
  };
  await page.setViewportSize({width:390,height:844});
  await page.goto(base);
  await page.waitForTimeout(1900);
  check('Mobile booking bar does not overlap hero copy',await page.evaluate(()=>{
    const bar=document.querySelector('.booking-bar').getBoundingClientRect();
    return ['.hero h1','.hero-lead','.hero .btn-row'].every(selector=>{const box=document.querySelector(selector).getBoundingClientRect();return bar.top>=box.bottom;});
  }));
  await page.evaluate(()=>scrollTo({top:2400,behavior:'instant'}));
  await page.waitForTimeout(300);
  await page.evaluate(()=>scrollTo({top:2300,behavior:'instant'}));
  await page.waitForTimeout(600);
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.waitForTimeout(700);
  check('Mobile drawer opens on the right after scrolling',await page.getByRole('dialog',{name:'Site menu'}).evaluate(el=>{const r=el.getBoundingClientRect();return r.right===innerWidth&&r.top===0&&r.bottom===innerHeight;}));
  check('Drawer moves focus to its close button',await page.evaluate(()=>document.activeElement.classList.contains('drawer-close')));
  await page.keyboard.press('Shift+Tab');
  check('Mobile menu keeps keyboard focus',await page.evaluate(()=>document.activeElement.textContent.includes('WhatsApp')));
  await page.keyboard.press('Escape');
  check('Escape closes menu and restores focus',await page.getByRole('button',{name:'Open menu'}).evaluate(el=>el===document.activeElement && el.getAttribute('aria-expanded')==='false'));
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.getByLabel('Check-in date',{exact:true}).fill(date(-1));
  check('Past check-in rejected',await page.getByLabel('Check-in date',{exact:true}).evaluate(el=>!el.checkValidity()));
  await page.getByLabel('Check-in date',{exact:true}).fill(date(5));
  await page.getByLabel('Check-out date',{exact:true}).fill(date(5));
  check('Same-day check-out rejected',await page.getByLabel('Check-out date',{exact:true}).evaluate(el=>!el.checkValidity()));
  await page.getByLabel('Check-out date',{exact:true}).fill(date(8));
  await page.getByLabel('Number of guests').selectOption('4');
  await page.getByRole('button',{name:'Check Availability'}).click();
  await page.waitForURL('**/book-your-stay/**');
  check('Booking bar carries dates and group size',await page.getByLabel('Check-in *',{exact:true}).inputValue()===date(5) && await page.getByLabel('Check-out *',{exact:true}).inputValue()===date(8) && await page.getByRole('combobox',{name:/^Adults/}).inputValue()==='4');
  await page.getByLabel('Your name *',{exact:true}).fill('QA Guest & Family');
  await page.getByLabel('Mobile number *',{exact:true}).fill('letters');
  check('Invalid mobile number rejected',await page.getByLabel('Mobile number *',{exact:true}).evaluate(el=>!el.checkValidity()));
  await page.getByLabel('Mobile number *',{exact:true}).fill('+91 90000 00000');
  await page.getByRole('combobox',{name:/^Children/}).selectOption('1');
  await page.getByLabel('Anything else we should know?').fill('Test enquiry only: 1 child aged 7. Quiet room? & arrival details.');
  await page.getByRole('button',{name:'Prepare WhatsApp Enquiry'}).click();
  const bookingLink=await page.getByRole('link',{name:'Open WhatsApp with My Enquiry'}).getAttribute('href');
  const bookingText=new URL(bookingLink).searchParams.get('text');
  check('Booking message contains encoded personal and travel details',bookingText.includes('QA Guest & Family')&&bookingText.includes('Adults: 4')&&bookingText.includes('Children: 1')&&bookingText.includes(date(5))&&bookingText.includes('Quiet room? & arrival details.'));
  check('Review states nothing has been sent',await page.getByText('Nothing has been sent yet.',{exact:false}).isVisible());
  check('Prepared message receives keyboard focus',await page.getByRole('link',{name:'Open WhatsApp with My Enquiry'}).evaluate(el=>el===document.activeElement));
  await page.screenshot({path:'output/playwright/enquiry-mobile.png',fullPage:true});
  await page.getByLabel('Your name *',{exact:true}).fill('Changed Guest');
  check('Editing invalidates the old summary',!await page.getByRole('link',{name:'Open WhatsApp with My Enquiry'}).isVisible());
  await page.goto(base+'/book-your-stay/?checkin=2020-01-01&checkout=2020-01-03&guests=999');
  check('Stale or manipulated URL values are ignored',await page.getByLabel('Check-in *',{exact:true}).inputValue()===''&&await page.getByRole('combobox',{name:/^Adults/}).inputValue()==='2');
  await page.goto(base+'/contact-us/');
  await page.getByLabel('Your name *',{exact:true}).fill('QA Contact');
  await page.getByLabel('Mobile number *',{exact:true}).fill('+91 90000 00000');
  await page.getByLabel('Your message *',{exact:true}).fill('Testing only, please share arrival information.');
  await page.getByLabel('Check-in (optional)',{exact:true}).fill(date(10));
  check('Contact form rejects incomplete date pairs',await page.getByLabel('Check-out (optional)',{exact:true}).evaluate(el=>!el.checkValidity()));
  await page.getByLabel('Check-in (optional)',{exact:true}).fill('');
  await page.getByRole('button',{name:'Prepare WhatsApp Enquiry'}).click();
  check('Contact enquiry works without optional dates or email',await page.getByRole('link',{name:'Open WhatsApp with My Enquiry'}).isVisible());
  await page.goto(base+'/gallery/');
  await page.getByRole('button',{name:'Accommodation',exact:true}).click();
  check('Gallery filter shows only accommodation photos',await page.locator('[data-gallery-item]:visible').count()===4);
  const first=page.getByRole('link',{name:'View photo: A room to make yourself at home',exact:true});
  await first.click();
  check('Photo viewer opens',await page.getByRole('dialog').isVisible());
  await page.keyboard.press('ArrowRight');
  check('Keyboard advances within filtered gallery',(await page.locator('#lightbox-caption').innerText()).startsWith('2 / 4'));
  await page.keyboard.press('ArrowLeft');
  check('Keyboard previous photo works',(await page.locator('#lightbox-caption').innerText()).startsWith('1 / 4'));
  await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
  const modalIssues=await page.evaluate(async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));});
  check('Open photo viewer passes automated accessibility checks',modalIssues.length===0);
  await page.keyboard.press('Escape');
  check('Escape closes photo viewer and returns focus',!await page.getByRole('dialog').isVisible()&&await first.evaluate(el=>el===document.activeElement));
  await page.goto(base+'/faq/');
  const question=page.getByText('How can I get directions?',{exact:true});
  await question.click();
  check('FAQ opens natively',await question.evaluate(el=>el.parentElement.open));
  await question.press('Enter');
  check('FAQ keyboard toggle works',!await question.evaluate(el=>el.parentElement.open));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base);await preparePhotos();
  await page.screenshot({path:'output/playwright/home-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.goto(base);await preparePhotos();
  await page.screenshot({path:'output/playwright/home-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/rooms/');await preparePhotos();
  await page.screenshot({path:'output/playwright/rooms-desktop.png',fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});await page.goto(base);
  check('Reduced motion disables landscape animation',await page.locator('.hero-media img').evaluate(el=>getComputedStyle(el).animationName==='none'));
  check('Reduced motion leaves content visible',await page.locator('.section-head').first().evaluate(el=>getComputedStyle(el).opacity==='1'));
  await page.emulateMedia({reducedMotion:'no-preference'});
  const nojs=await page.context().browser().newContext({javaScriptEnabled:false,viewport:{width:320,height:900}});
  const fallback=await nojs.newPage();
  await fallback.goto(base);
  await fallback.locator('.menu-nojs').click();
  await fallback.waitForTimeout(800);
  check('No-JS menu opens via fallback link',await fallback.getByRole('navigation',{name:'Mobile navigation'}).isVisible());
  await fallback.goto(base);
  check('No-JS page has no overflow',await fallback.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+1));
  check('No-JS essential room content remains visible',await fallback.getByRole('heading',{name:'Comfortable rooms for a relaxing stay'}).isVisible());
  await fallback.goto(base+'/book-your-stay/');
  check('No-JS enquiry offers direct contact fallback',await fallback.locator('.no-js-note').isVisible()&&await fallback.getByRole('button',{name:'Prepare WhatsApp Enquiry'}).isDisabled());
  await nojs.close();
  return {checks,passed:checks.filter(c=>c.pass).length,total:checks.length,modalIssues,messageDelivery:'Not attempted; no WhatsApp link was opened or message sent.'};
}
